import { Pool } from "pg";
import { env } from "../config/env.js";

export const pool = new Pool({
  connectionString: env.databaseUrl,
  connectionTimeoutMillis: 5_000,
  idleTimeoutMillis: 30_000,
  max: 10,
});

let initialization: Promise<void> | undefined;

export function initializeDatabase() {
  if (!initialization) {
    initialization = (async () => {
      await pool.query(`
        CREATE TABLE IF NOT EXISTS users (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          email TEXT NOT NULL,
          name TEXT NOT NULL,
          password_hash TEXT NOT NULL,
          created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
      `);
      await pool.query(`
        CREATE UNIQUE INDEX IF NOT EXISTS users_email_lower_idx
        ON users (LOWER(email))
      `);
      await pool.query(`
        CREATE TABLE IF NOT EXISTS applications (
          id TEXT PRIMARY KEY,
          user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
          company TEXT NOT NULL,
          role TEXT NOT NULL,
          status TEXT NOT NULL CHECK (status IN ('applied', 'interview', 'offer', 'rejected')),
          applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
      `);
      await pool.query(`
        CREATE INDEX IF NOT EXISTS applications_user_status_idx
        ON applications (user_id, status)
      `);
      await pool.query(`
        CREATE TABLE IF NOT EXISTS refresh_tokens (
          token_hash CHAR(64) PRIMARY KEY,
          user_id BIGINT NOT NULL,
          expires_at TIMESTAMPTZ NOT NULL
        )
      `);
      await pool.query(`
        CREATE INDEX IF NOT EXISTS refresh_tokens_user_id_idx
        ON refresh_tokens (user_id)
      `);

      if (env.nodeEnv !== "production") {
        await pool.query(
          `INSERT INTO users (id, email, name, password_hash)
           SELECT 1, $1, $2, $3
           WHERE NOT EXISTS (
             SELECT 1 FROM users
             WHERE id = 1 OR LOWER(email) = LOWER($1)
           )
           ON CONFLICT DO NOTHING`,
          [
            "sonam@gmail.com",
            "Sonam Verma",
            "$2b$10$LdkBEeP0sfgEpFT6NP/rOeSWUscwIVix6mYNkWflFrM3YIlTXCcHO",
          ],
        );
        const seededUser = await pool.query<{ id: string }>(
          "SELECT id FROM users WHERE LOWER(email) = LOWER($1)",
          ["sonam@gmail.com"],
        );
        if (seededUser.rows[0]) {
          const seedUserId = Number(seededUser.rows[0].id);
          await pool.query(
            `INSERT INTO applications (id, user_id, company, role, status, applied_at)
             VALUES
               ('1', $1, 'Google', 'Frontend Developer', 'applied', '2026-09-30T10:30:00.000Z'),
               ('2', $1, 'Microsoft', 'React Developer', 'interview', '2026-09-30T10:30:00.000Z')
             ON CONFLICT (id) DO NOTHING`,
            [seedUserId],
          );
        }
        await pool.query(
          `SELECT setval(
            pg_get_serial_sequence('users', 'id'),
            GREATEST(COALESCE((SELECT MAX(id) FROM users), 1), 1),
            true
          )`,
        );
      }
    })().catch((error: unknown) => {
      initialization = undefined;
      throw error;
    });
  }
  return initialization;
}

export async function checkDatabase() {
  await pool.query("SELECT 1");
}

export async function closeDatabase() {
  await pool.end();
  initialization = undefined;
}
